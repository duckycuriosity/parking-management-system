-- Subscription periods are independent of the legacy ticket tables. Existing
-- vehicle, parking_lot and payment IDs are BIGINT; no owner tables are replaced.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE subscription_package (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_code VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    version_no INTEGER NOT NULL,
    parking_lot_id BIGINT NOT NULL REFERENCES parking_lot(id),
    vehicle_type VARCHAR(20) NOT NULL,
    price_vnd BIGINT NOT NULL,
    duration_days INTEGER NOT NULL,
    coverage_mode VARCHAR(20) NOT NULL,
    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    sale_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_subscription_package_code_version UNIQUE (package_code, version_no),
    CONSTRAINT uq_subscription_package_id_scope UNIQUE (id, parking_lot_id),
    CONSTRAINT ck_subscription_package_code CHECK (length(btrim(package_code)) > 0),
    CONSTRAINT ck_subscription_package_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_subscription_package_version CHECK (version_no > 0),
    CONSTRAINT ck_subscription_package_vehicle CHECK (vehicle_type IN ('CAR', 'MOTORBIKE')),
    CONSTRAINT ck_subscription_package_price CHECK (price_vnd >= 0),
    CONSTRAINT ck_subscription_package_duration CHECK (duration_days > 0),
    CONSTRAINT ck_subscription_package_coverage CHECK (coverage_mode IN ('ALL_DAY', 'WEEKLY')),
    CONSTRAINT ck_subscription_package_status CHECK (status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT ck_subscription_package_effective CHECK (
        effective_to IS NULL OR effective_to > effective_from
    ),
    CONSTRAINT ex_subscription_package_published_overlap EXCLUDE USING gist (
        package_code WITH =,
        tstzrange(effective_from, effective_to, '[)') WITH &&
    ) WHERE (status = 'PUBLISHED')
);

CREATE INDEX idx_subscription_package_catalog
    ON subscription_package(parking_lot_id, vehicle_type, effective_from);

CREATE TABLE subscription_package_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id BIGINT NOT NULL REFERENCES subscription_package(id),
    weekday INTEGER NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_subscription_package_schedule_weekday CHECK (weekday BETWEEN 1 AND 7),
    CONSTRAINT ck_subscription_package_schedule_clock CHECK (
        start_time < TIME '24:00:00' AND end_time < TIME '24:00:00'
    ),
    CONSTRAINT uq_subscription_package_schedule_window UNIQUE (
        package_id, weekday, start_time, end_time
    )
);

CREATE INDEX idx_subscription_package_schedule_package
    ON subscription_package_schedule(package_id);

CREATE TABLE vehicle_subscription (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key VARCHAR(100) NOT NULL,
    vehicle_id BIGINT NOT NULL REFERENCES vehicle(id),
    parking_lot_id BIGINT NOT NULL REFERENCES parking_lot(id),
    package_id BIGINT NOT NULL,
    previous_subscription_id BIGINT,
    registration_type VARCHAR(20) NOT NULL,
    price_vnd BIGINT NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    payment_deadline_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING_PAYMENT',
    paid_at TIMESTAMPTZ,
    paid_receipt_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_vehicle_subscription_request_key UNIQUE (request_key),
    CONSTRAINT uq_vehicle_subscription_paid_receipt UNIQUE (paid_receipt_id),
    CONSTRAINT uq_vehicle_subscription_id_scope UNIQUE (id, vehicle_id, parking_lot_id),
    CONSTRAINT fk_vehicle_subscription_package_scope FOREIGN KEY (package_id, parking_lot_id)
        REFERENCES subscription_package(id, parking_lot_id),
    CONSTRAINT fk_vehicle_subscription_previous_scope FOREIGN KEY (
        previous_subscription_id, vehicle_id, parking_lot_id
    ) REFERENCES vehicle_subscription(id, vehicle_id, parking_lot_id),
    CONSTRAINT ck_vehicle_subscription_request CHECK (length(btrim(request_key)) > 0),
    CONSTRAINT ck_vehicle_subscription_price CHECK (price_vnd >= 0),
    CONSTRAINT ck_vehicle_subscription_period CHECK (ends_at > starts_at),
    CONSTRAINT ck_vehicle_subscription_status CHECK (
        status IN ('PENDING_PAYMENT', 'PAID', 'CANCELLED', 'PAYMENT_EXCEPTION')
    ),
    CONSTRAINT ck_vehicle_subscription_registration CHECK (
        (registration_type = 'NEW' AND previous_subscription_id IS NULL)
        OR (registration_type = 'RENEW' AND previous_subscription_id IS NOT NULL
            AND previous_subscription_id <> id)
    ),
    CONSTRAINT ck_vehicle_subscription_paid CHECK (
        (status = 'PAID' AND paid_at IS NOT NULL AND paid_receipt_id IS NOT NULL
            AND paid_at <= payment_deadline_at)
        OR (status <> 'PAID' AND paid_at IS NULL AND paid_receipt_id IS NULL)
    ),
    CONSTRAINT ex_vehicle_subscription_paid_overlap EXCLUDE USING gist (
        vehicle_id WITH =,
        parking_lot_id WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status = 'PAID')
);

CREATE INDEX idx_vehicle_subscription_vehicle_period
    ON vehicle_subscription(vehicle_id, parking_lot_id, starts_at);
CREATE INDEX idx_vehicle_subscription_previous ON vehicle_subscription(previous_subscription_id);
CREATE INDEX idx_vehicle_subscription_package ON vehicle_subscription(package_id);

CREATE TABLE vehicle_subscription_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES vehicle_subscription(id),
    payment_id BIGINT NOT NULL REFERENCES payment(id),
    source VARCHAR(50) NOT NULL,
    reference VARCHAR(100) NOT NULL,
    invoice_no VARCHAR(100) NOT NULL,
    currency VARCHAR(10) NOT NULL,
    amount_vnd BIGINT NOT NULL,
    paid_at TIMESTAMPTZ,
    received_at TIMESTAMPTZ NOT NULL,
    outcome VARCHAR(30) NOT NULL,
    reason_code VARCHAR(100),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_subscription_receipt_source_reference UNIQUE (source, reference),
    CONSTRAINT uq_subscription_receipt_id_parent UNIQUE (id, subscription_id),
    CONSTRAINT ck_subscription_receipt_identifiers CHECK (
        length(btrim(source)) > 0 AND length(btrim(reference)) > 0
        AND length(btrim(invoice_no)) > 0 AND length(btrim(currency)) > 0
    ),
    CONSTRAINT ck_subscription_receipt_amount CHECK (amount_vnd >= 0),
    CONSTRAINT ck_subscription_receipt_metadata CHECK (jsonb_typeof(metadata) = 'object'),
    CONSTRAINT ck_subscription_receipt_outcome CHECK (
        (outcome = 'APPLIED' AND paid_at IS NOT NULL AND currency = 'VND' AND reason_code IS NULL)
        OR (outcome = 'REVIEW_REQUIRED' AND reason_code IS NOT NULL
            AND length(btrim(reason_code)) > 0)
    )
);

-- There is deliberately no UNIQUE(payment_id): two bank transfers can target
-- one invoice. The physical settlement identity is source + reference.
CREATE INDEX idx_subscription_receipt_payment ON vehicle_subscription_receipt(payment_id);
CREATE INDEX idx_subscription_receipt_parent_received
    ON vehicle_subscription_receipt(subscription_id, received_at, id);

ALTER TABLE vehicle_subscription ADD CONSTRAINT fk_vehicle_subscription_paid_receipt_parent
    FOREIGN KEY (paid_receipt_id, id)
    REFERENCES vehicle_subscription_receipt(id, subscription_id);

CREATE FUNCTION enforce_subscription_package_contract() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    overlapping_schedule BOOLEAN;
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status = 'PUBLISHED' THEN
            RAISE EXCEPTION 'A published subscription package cannot be deleted';
        END IF;
        RETURN OLD;
    END IF;

    -- A code identifies one stable lot/type across all versions. Serializing
    -- that code also protects concurrent INSERTs before any version exists.
    PERFORM pg_advisory_xact_lock(hashtextextended(NEW.package_code, 20261009));
    IF EXISTS (
        SELECT 1 FROM subscription_package p
        WHERE p.package_code = NEW.package_code AND p.id <> NEW.id
          AND (p.parking_lot_id <> NEW.parking_lot_id OR p.vehicle_type <> NEW.vehicle_type)
    ) THEN
        RAISE EXCEPTION 'A package code cannot change parking lot or vehicle type';
    END IF;

    IF TG_OP = 'UPDATE' AND OLD.status = 'PUBLISHED'
       AND (to_jsonb(OLD) - ARRAY['sale_enabled', 'effective_to', 'updated_at'])
           IS DISTINCT FROM
           (to_jsonb(NEW) - ARRAY['sale_enabled', 'effective_to', 'updated_at']) THEN
        RAISE EXCEPTION 'Published package terms are immutable; create a new version';
    END IF;

    -- Draft schedules are entered first, then the package is published.
    -- Existing versions only change their sale flag/end, never these terms.
    IF NEW.status = 'PUBLISHED' AND (TG_OP = 'INSERT' OR OLD.status <> 'PUBLISHED') THEN
        IF NEW.coverage_mode = 'ALL_DAY' AND EXISTS (
            SELECT 1 FROM subscription_package_schedule WHERE package_id = NEW.id
        ) THEN
            RAISE EXCEPTION 'ALL_DAY packages must not contain weekly schedules';
        ELSIF NEW.coverage_mode = 'WEEKLY' THEN
            IF NOT EXISTS (SELECT 1 FROM subscription_package_schedule WHERE package_id = NEW.id) THEN
                RAISE EXCEPTION 'WEEKLY packages require at least one schedule';
            END IF;

            -- Split Sunday windows wrapping into Monday into two ranges of
            -- the same repeating week. Adjacent half-open windows are valid.
            WITH raw_windows AS (
                SELECT (weekday - 1)::numeric * 86400 + extract(epoch FROM start_time) AS a,
                       (weekday - 1)::numeric * 86400 + extract(epoch FROM end_time)
                           + CASE WHEN end_time <= start_time THEN 86400 ELSE 0 END AS b
                FROM subscription_package_schedule WHERE package_id = NEW.id
            ), windows AS (
                SELECT a, least(b, 604800::numeric) AS b FROM raw_windows
                UNION ALL
                SELECT 0::numeric, b - 604800 FROM raw_windows WHERE b > 604800
            ), ordered_windows AS (
                SELECT a, b, lag(b) OVER (ORDER BY a, b) AS previous_end FROM windows
            )
            SELECT EXISTS (SELECT 1 FROM ordered_windows WHERE a < previous_end)
                INTO overlapping_schedule;
            IF overlapping_schedule THEN
                RAISE EXCEPTION 'Weekly subscription schedule windows must not overlap';
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_subscription_package_contract
    BEFORE INSERT OR UPDATE OR DELETE ON subscription_package
    FOR EACH ROW EXECUTE FUNCTION enforce_subscription_package_contract();

CREATE FUNCTION enforce_subscription_schedule_immutability() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    parent_status VARCHAR(20);
BEGIN
    IF TG_OP <> 'INSERT' THEN
        SELECT status INTO parent_status FROM subscription_package WHERE id = OLD.package_id FOR UPDATE;
        IF parent_status = 'PUBLISHED' THEN
            RAISE EXCEPTION 'Published package schedules cannot be changed';
        END IF;
    END IF;
    IF TG_OP <> 'DELETE' THEN
        SELECT status INTO parent_status FROM subscription_package WHERE id = NEW.package_id FOR UPDATE;
        IF parent_status = 'PUBLISHED' THEN
            RAISE EXCEPTION 'Published package schedules cannot be changed';
        END IF;
        RETURN NEW;
    END IF;
    RETURN OLD;
END $$;

CREATE TRIGGER trg_subscription_schedule_immutable
    BEFORE INSERT OR UPDATE OR DELETE ON subscription_package_schedule
    FOR EACH ROW EXECUTE FUNCTION enforce_subscription_schedule_immutability();

CREATE FUNCTION enforce_vehicle_subscription_contract() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    package_row subscription_package%ROWTYPE;
    previous_row vehicle_subscription%ROWTYPE;
    receipt_row vehicle_subscription_receipt%ROWTYPE;
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status = 'PAID' THEN
            RAISE EXCEPTION 'A paid subscription period cannot be deleted';
        END IF;
        RETURN OLD;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.status = 'PAID' AND (to_jsonb(OLD) - 'updated_at')
                IS DISTINCT FROM (to_jsonb(NEW) - 'updated_at') THEN
            RAISE EXCEPTION 'A paid subscription period is immutable';
        END IF;
        IF (to_jsonb(OLD) - ARRAY['status', 'paid_at', 'paid_receipt_id', 'updated_at'])
                IS DISTINCT FROM
                (to_jsonb(NEW) - ARRAY['status', 'paid_at', 'paid_receipt_id', 'updated_at']) THEN
            RAISE EXCEPTION 'Quoted subscription terms are immutable';
        END IF;
    ELSE
        SELECT * INTO package_row FROM subscription_package WHERE id = NEW.package_id FOR SHARE;
        IF NOT FOUND OR package_row.status <> 'PUBLISHED' THEN
            RAISE EXCEPTION 'A subscription must reference a published package version';
        END IF;
        IF NEW.price_vnd <> package_row.price_vnd
            OR NEW.ends_at - NEW.starts_at <> make_interval(days => package_row.duration_days) THEN
            RAISE EXCEPTION 'Quoted price and N x 24 hour duration must match the package version';
        END IF;
        IF NEW.registration_type = 'RENEW' THEN
            SELECT * INTO previous_row FROM vehicle_subscription WHERE id = NEW.previous_subscription_id;
            IF NOT FOUND OR previous_row.status <> 'PAID' OR NEW.starts_at <> previous_row.ends_at THEN
                RAISE EXCEPTION 'Renewal must continue at the paid predecessor end';
            END IF;
        END IF;
    END IF;

    IF NEW.status = 'PAID' THEN
        -- The receipt is inserted/flushed while its parent is still pending;
        -- only this subsequent PAID update requires the APPLIED linkage.
        SELECT * INTO receipt_row FROM vehicle_subscription_receipt WHERE id = NEW.paid_receipt_id;
        IF NOT FOUND OR receipt_row.subscription_id <> NEW.id OR receipt_row.outcome <> 'APPLIED'
            OR receipt_row.amount_vnd <> NEW.price_vnd OR receipt_row.currency <> 'VND'
            OR receipt_row.paid_at IS DISTINCT FROM NEW.paid_at THEN
            RAISE EXCEPTION 'Paid subscription must reference its own matching applied receipt';
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_vehicle_subscription_contract
    BEFORE INSERT OR UPDATE OR DELETE ON vehicle_subscription
    FOR EACH ROW EXECUTE FUNCTION enforce_vehicle_subscription_contract();

CREATE FUNCTION enforce_subscription_receipt_immutability() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Subscription receipts are append-only audit records';
END $$;

CREATE TRIGGER trg_subscription_receipt_immutable
    BEFORE UPDATE OR DELETE ON vehicle_subscription_receipt
    FOR EACH ROW EXECUTE FUNCTION enforce_subscription_receipt_immutability();

CREATE FUNCTION ensure_applied_subscription_receipt_grants_period() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    subscription_row vehicle_subscription%ROWTYPE;
BEGIN
    SELECT * INTO subscription_row FROM vehicle_subscription WHERE id = NEW.subscription_id;
    IF NOT FOUND OR subscription_row.status <> 'PAID'
        OR subscription_row.paid_receipt_id IS DISTINCT FROM NEW.id
        OR subscription_row.price_vnd IS DISTINCT FROM NEW.amount_vnd
        OR subscription_row.paid_at IS DISTINCT FROM NEW.paid_at
        OR NEW.currency <> 'VND' THEN
        RAISE EXCEPTION 'An APPLIED receipt must grant its matching subscription period in the same transaction';
    END IF;
    RETURN NEW;
END $$;

-- The service intentionally flushes the receipt before writing the PAID parent.
-- Defer this reciprocal audit guarantee until COMMIT so that intermediate
-- ordering remains valid while a committed APPLIED receipt always grants rights.
CREATE CONSTRAINT TRIGGER trg_subscription_receipt_applied_at_commit
    AFTER INSERT ON vehicle_subscription_receipt
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW WHEN (NEW.outcome = 'APPLIED')
    EXECUTE FUNCTION ensure_applied_subscription_receipt_grants_period();

COMMENT ON COLUMN subscription_package.package_code IS
    'Stable business code; all versions belong to the same parking lot and vehicle type.';
COMMENT ON COLUMN subscription_package.duration_days IS
    'Each subscription period lasts exactly N x 24 hours, not calendar months.';
COMMENT ON COLUMN subscription_package_schedule.weekday IS
    '1=Monday, 2=Tuesday, 3=Wednesday, 4=Thursday, 5=Friday, 6=Saturday, 7=Sunday.';
COMMENT ON COLUMN subscription_package_schedule.end_time IS
    'Greater than start: same day; less than start: next day; equal: 24 hours from start.';
COMMENT ON COLUMN vehicle_subscription.status IS
    'Payment state, not a statement that the vehicle is currently covered by its schedule.';
COMMENT ON COLUMN vehicle_subscription_receipt.paid_at IS
    'Verified instant of physical settlement; NULL if the source cannot supply a reliable timestamp.';
COMMENT ON COLUMN vehicle_subscription_receipt.metadata IS
    'Whitelisted verification facts only; never raw callback payloads, secrets or credentials.';
