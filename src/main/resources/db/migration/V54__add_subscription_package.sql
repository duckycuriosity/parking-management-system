CREATE TABLE IF NOT EXISTS subscription_package (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    package_code VARCHAR(100),
    name VARCHAR(255),
    version_no INTEGER,
    parking_lot_id BIGINT not null,
    vehicle_type VARCHAR(20),
    price_vnd NUMERIC(18,2),
    duration_days INTEGER,
    coverage_mode VARCHAR(20),
    effective_from TIMESTAMPTZ,
    effective_to TIMESTAMPTZ,
    status VARCHAR(20) DEFAULT 'DRAFT',
    sale_enabled BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_subscription_package_catalog
    ON subscription_package(parking_lot_id, vehicle_type, effective_from);

CREATE TABLE IF NOT EXISTS subscription_package_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    package_id BIGINT not null,
    weekday INTEGER,
    start_time TIME,
    end_time TIME,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_subscription_package_schedule_package
    ON subscription_package_schedule(package_id);
